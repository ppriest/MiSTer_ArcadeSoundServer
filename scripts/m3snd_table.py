# arcsnd's Model 3 sound ROM table from Supermodel's Games.xml: for every set in it that has a sound board (a
# sound_program, its own or its parent's), its parent and the files of its sound_program and sound_samples
# regions (name, offset, size, CRC-32); the session claims every set in the table, so a new Model 3 game needs
# no change to the server,
# a clone's regions from its parent where it has none; and for the sets with a Digital Sound Board
# (mpeg_board DSB1 / DSB2) its mpeg_program and mpeg_music regions. The program is used in the zip's
# own byte order, as the SCSP's is: Games.xml marks DSB2's byte_swap, and with Supermodel's loader the
# result is the zip's order (a swapped copy boots the 68000 at an odd PC and never plays). No ROM
# data: names and numbers only.
#   m3snd_table.py <Games.xml> > roms_table.h
import sys, xml.etree.ElementTree as ET, zlib
games = {g.get('name'): g for g in ET.parse(sys.argv[1]).getroot().iter('game')}
def region_el(name, r):
    g = games[name]
    for x in g.iter('region'):
        if x.get('name') == r:
            return x
    p = g.get('parent')
    return region_el(p, r) if p else None
def region(name, r):
    x = region_el(name, r)
    return [(f.get('name'), int(f.get('offset'), 0), int(f.get('crc32'), 0)) for f in x.iter('file')] if x is not None else []
# every set with a sound program, in Games.xml's order (Supermodel's pro1000 has none)
SETS = [n for n in games if region_el(n, 'sound_program') is not None]
NOSND = [n for n in games if n not in SETS]
def board(name):
    g = games[name]
    for x in g.iter('mpeg_board'):
        return {'DSB1': 1, 'DSB2': 2}.get(x.text.strip(), 0)
    p = g.get('parent')
    return board(p) if p else 0
print("// SPDX-License-Identifier: GPL-3.0-or-later")
print("// Generated by scripts/m3snd_table.py from Supermodel's Config/Games.xml (036af1c):")
print("// each set's parent and its sound ROMs (file, offset in the region, CRC-32). No ROM data.")
print("// Every set with a sound board; left out (no sound program): %s." % (', '.join(NOSND) or 'none'))
print("#pragma once\n#include <cstdint>\n")
print("struct m3snd_file { const char *name; uint32_t offset, crc; };")
print("struct m3snd_set { const char *name, *parent; m3snd_file prog[2], smp[5]; };\n")
print("static const m3snd_set M3SND_SETS[] = {")
for s in SETS:
    par = games[s].get('parent') or ''
    pr = region(s, 'sound_program'); sm = region(s, 'sound_samples')
    f = lambda l, n: ', '.join(['{"%s", 0x%X, 0x%08X}' % x for x in l] + ['{nullptr, 0, 0}'] * (n - len(l)))
    print('\t{"%s", "%s", {%s}, {%s}},' % (s, par, f(pr, 2), f(sm, 5)))
print("};")
print("\n// the Digital Sound Board: its type (1 Z80, 2 68000), its program (128 KB, in the zip's byte order:")
print("// DSB2's 68000 words little-endian, as the SCSP program's) and its MPEG music (16 MB)")
print("struct m3dsb_set { const char *name, *parent; int type; m3snd_file prog[2], mpeg[5]; };\n")
print("static const m3dsb_set M3DSB_SETS[] = {")
for s in SETS:
    t = board(s)
    if not t: continue
    par = games[s].get('parent') or ''
    pr = region(s, 'mpeg_program'); mu = region(s, 'mpeg_music')
    f = lambda l, n: ', '.join(['{"%s", 0x%X, 0x%08X}' % x for x in l] + ['{nullptr, 0, 0}'] * (n - len(l)))
    print('\t{"%s", "%s", %d, {%s}, {%s}},' % (s, par, t, f(pr, 2), f(mu, 5)))
print("};")
